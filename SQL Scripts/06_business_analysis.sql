-- OBJECTIVE 1: PIPELINE METRICS
-- ==================================================================================

-- 1. Calculate the number of sales opportunities created each month using "engage_date",
-- and identify the month with the most opportunities.
PRINT '--- Objective 1.1: Opportunities Created Each Month ---';
SELECT 
    FORMAT(engage_date, 'yyyy-MM') AS engagement_month,
    COUNT(*) AS opportunities_count
FROM vw_sales_pipeline
WHERE engage_date IS NOT NULL
GROUP BY FORMAT(engage_date, 'yyyy-MM')
ORDER BY engagement_month ASC;

-- Query to isolate the single peak month with the highest velocity
SELECT TOP 1
    FORMAT(engage_date, 'yyyy-MM') AS top_engagement_month,
    COUNT(*) AS opportunities_count
FROM vw_sales_pipeline
WHERE engage_date IS NOT NULL
GROUP BY FORMAT(engage_date, 'yyyy-MM')
ORDER BY opportunities_count DESC;


-- 2. Find the average time deals stayed open (from "engage_date" to "close_date"),
-- and compare closed deals versus won deals.
PRINT '--- Objective 1.2: Average Time Deals Stayed Open (Days) ---';
SELECT 
    deal_stage,
    COUNT(*) AS deal_count,
    AVG(DATEDIFF(day, engage_date, close_date)) AS avg_days_open
FROM vw_sales_pipeline
WHERE engage_date IS NOT NULL AND close_date IS NOT NULL
GROUP BY deal_stage
UNION ALL
SELECT 
    'All Closed Deals (Won & Lost)' AS deal_stage,
    COUNT(*) AS deal_count,
    AVG(DATEDIFF(day, engage_date, close_date)) AS avg_days_open
FROM vw_sales_pipeline
WHERE engage_date IS NOT NULL AND close_date IS NOT NULL AND deal_stage IN ('Won', 'Lost');


-- 3. Calculate the percentage of deals in each stage, and determine what share were lost.
PRINT '--- Objective 1.3: Percentage of Deals in Each Stage ---';
SELECT 
    deal_stage,
    COUNT(*) AS total_deals,
    CAST(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER() AS DECIMAL(5,2)) AS percentage_share
FROM vw_sales_pipeline
GROUP BY deal_stage
ORDER BY percentage_share DESC;


-- 4. Compute the win rate for each product, and identify which one had the highest win rate.
PRINT '--- Objective 1.4: Win Rate by Product ---';
SELECT 
    product,
    COUNT(CASE WHEN deal_stage = 'Won' THEN 1 END) AS won_deals,
    COUNT(CASE WHEN deal_stage IN ('Won', 'Lost') THEN 1 END) AS total_closed_deals,
    CAST(COUNT(CASE WHEN deal_stage = 'Won' THEN 1 END) * 100.0 / 
         NULLIF(COUNT(CASE WHEN deal_stage IN ('Won', 'Lost') THEN 1 END), 0) AS DECIMAL(5,2)) AS win_rate_percentage
FROM vw_sales_pipeline
GROUP BY product
ORDER BY win_rate_percentage DESC;


-- ==================================================================================
-- OBJECTIVE 2: SALES AGENT PERFORMANCE
-- ==================================================================================

-- 1. Calculate the win rate for each sales agent, and find the top performer.
PRINT '--- Objective 2.1: Win Rate by Sales Agent ---';
SELECT 
    sales_agent,
    COUNT(CASE WHEN deal_stage = 'Won' THEN 1 END) AS won_deals,
    COUNT(CASE WHEN deal_stage IN ('Won', 'Lost') THEN 1 END) AS total_closed_deals,
    CAST(COUNT(CASE WHEN deal_stage = 'Won' THEN 1 END) * 100.0 / 
         NULLIF(COUNT(CASE WHEN deal_stage IN ('Won', 'Lost') THEN 1 END), 0) AS DECIMAL(5,2)) AS win_rate_percentage
FROM vw_sales_pipeline
GROUP BY sales_agent
ORDER BY win_rate_percentage DESC;


-- 2. Calculate the total revenue by agent, and see who generated the most.
PRINT '--- Objective 2.2: Total Revenue Generated by Agent ---';
SELECT 
    sales_agent,
    SUM(close_value) AS total_revenue
FROM vw_sales_pipeline
WHERE deal_stage = 'Won'
GROUP BY sales_agent
ORDER BY total_revenue DESC;


-- 3. Calculate win rates by manager to determine which manager’s team performed best.
PRINT '--- Objective 2.3: Win Rates by Manager ---';
SELECT
    st.manager,
    COUNT(CASE WHEN sp.deal_stage = 'Won' THEN 1 END) AS won_deals,
    COUNT(CASE WHEN sp.deal_stage IN ('Won', 'Lost') THEN 1 END) AS closed_deals,
    CAST(COUNT(CASE WHEN sp.deal_stage = 'Won' THEN 1 END) * 100.0
        /
        NULLIF(COUNT(CASE WHEN sp.deal_stage IN ('Won', 'Lost') THEN 1 END), 0
        )
        AS DECIMAL(5,2)
    ) AS win_rate_percentage
FROM vw_sales_pipeline AS sp
JOIN vw_sales_teams AS st
    ON sp.sales_agent = st.sales_agent
GROUP BY st.manager
ORDER BY win_rate_percentage DESC;


-- 4. For the product GTX Plus Pro, find which regional office sold the most units.
PRINT '--- Objective 2.4: GTX Plus Pro Units Sold by Regional Office ---';
SELECT
    st.regional_office,
    COUNT(*) AS units_sold
FROM vw_sales_pipeline sp
INNER JOIN vw_sales_teams st
    ON sp.sales_agent = st.sales_agent
WHERE sp.product = 'GTX Plus Pro'
    AND sp.deal_stage = 'Won'
GROUP BY st.regional_office
ORDER BY units_sold DESC;


-- ==================================================================================
-- OBJECTIVE 3: PRODUCT ANALYSIS
-- ==================================================================================

-- 1. For March deals, identify the top product by revenue and compare it to the top by units sold.
PRINT '--- Objective 3.1: March Deals - Revenue vs Units Sold by Product ---';
SELECT
    product,
    SUM(close_value) AS total_revenue,
    COUNT(*) AS units_sold
FROM vw_sales_pipeline
WHERE MONTH(close_date) = 3
    AND deal_stage = 'Won'
GROUP BY product
ORDER BY total_revenue DESC;


-- 2. Calculate the average difference between "sales_price" and "close_value" for each product, 
-- and note if the results suggest a data issue.
PRINT '--- Objective 3.2: Price Variance and Potential Data Issues ---';
SELECT 
    p.product,
    AVG(pr.sales_price) AS standard_sales_price,
    AVG(p.close_value) AS avg_close_value,
    AVG(pr.sales_price - p.close_value) AS avg_price_difference,
    AVG((pr.sales_price - p.close_value) / NULLIF(pr.sales_price, 0)) * 100.0 AS avg_discount_percentage
FROM vw_sales_pipeline p
JOIN vw_products pr ON p.product = pr.product
WHERE p.deal_stage = 'Won'
GROUP BY p.product;

