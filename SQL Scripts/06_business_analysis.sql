    'Annual Corporate Revenue (Millions USD)' AS metric_type,
    SUM(revenue) AS total_value
FROM vw_accounts
WHERE account = 'Acme Corp' OR subsidiary_of = 'Acme Corp';

-- Interpretation B: Sum of Won Sales Values from the Pipeline (CRM Performance in USD)
SELECT 
    'Won Pipeline Sales Revenue (USD)' AS metric_type,
    SUM(p.close_value) AS total_value
FROM vw_sales_pipeline p
JOIN vw_accounts a ON p.account = a.account
WHERE (a.account = 'Acme Corp' OR a.subsidiary_of = 'Acme Corp') 
  AND p.deal_stage = 'Won';