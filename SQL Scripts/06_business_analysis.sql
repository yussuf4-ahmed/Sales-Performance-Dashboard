-- 3. Calculate total revenue by product series and compare their performance.
PRINT '--- Objective 3.3: Total Revenue by Product Series ---';
SELECT 
    pr.series,
    SUM(p.close_value) AS total_revenue,
    COUNT(p.opportunity_id) AS total_deals_won
FROM vw_sales_pipeline p
JOIN vw_products pr ON p.product = pr.product
WHERE p.deal_stage = 'Won'
GROUP BY pr.series
ORDER BY total_revenue DESC;


-- ==================================================================================
-- OBJECTIVE 4: ACCOUNT ANALYSIS
-- ==================================================================================

-- 1. Calculate revenue by office location, and identify the lowest performer.
PRINT '--- Objective 4.1: Revenue by Client Office Location ---';
SELECT 
    a.office_location,
    SUM(p.close_value) AS total_revenue
FROM vw_sales_pipeline p
JOIN vw_accounts a ON p.account = a.account
WHERE p.deal_stage = 'Won'
GROUP BY a.office_location
ORDER BY total_revenue ASC;


-- 2. Find the gap in years between the oldest and newest customer, and name those companies.
PRINT '--- Objective 4.2: Customer Age Span and Extreme Companies ---';
WITH AgeBounds AS (
    SELECT 
        MIN(year_established) AS oldest_year,
        MAX(year_established) AS newest_year,
        MAX(year_established) - MIN(year_established) AS year_gap
    FROM vw_accounts
)
SELECT 
    (SELECT year_gap FROM AgeBounds) AS year_gap,
    a.account AS company_name,
    a.year_established,
    CASE 
        WHEN a.year_established = (SELECT oldest_year FROM AgeBounds) THEN 'Oldest Customer'
        WHEN a.year_established = (SELECT newest_year FROM AgeBounds) THEN 'Newest Customer'
    END AS customer_status
FROM vw_accounts a
WHERE a.year_established = (SELECT oldest_year FROM AgeBounds)
   OR a.year_established = (SELECT newest_year FROM AgeBounds);


-- 3. Which accounts that were subsidiaries had the most lost sales opportunities?
PRINT '--- Objective 4.3: Lost Opportunities for Subsidiary Accounts ---';
SELECT 
    p.account AS subsidiary_account,
    a.subsidiary_of AS parent_company,
    COUNT(*) AS lost_deals_count
FROM vw_sales_pipeline p
JOIN vw_accounts a ON p.account = a.account
WHERE a.subsidiary_of IS NOT NULL AND p.deal_stage = 'Lost'
GROUP BY p.account, a.subsidiary_of
ORDER BY lost_deals_count DESC;


-- 4. Join the companies to their subsidiaries. Which parent group had the highest total company revenue?
PRINT '--- Objective 4.4: Parent-Subsidiary Structure and Corporate Revenue ---';
SELECT 
    p.account AS parent_company,
    p.revenue AS parent_annual_revenue,
    SUM(s.revenue) AS combined_subsidiaries_annual_revenue,
    (p.revenue + SUM(s.revenue)) AS total_corporate_group_revenue
FROM vw_accounts p
JOIN vw_accounts s ON s.subsidiary_of = p.account
GROUP BY p.account, p.revenue
ORDER BY total_corporate_group_revenue DESC;


